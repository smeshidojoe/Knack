"""
Масштаб интерфейса.

Макет нарисован под 2560 логических пикселей ширины. Коэффициент считаем от
ЛОГИЧЕСКОЙ геометрии экрана, а не физической: Qt6 сам применяет DPI-масштаб
Windows, и на 2560x1440 при 150% экран логически 1707x960. Считать от физической
ширины значило бы уменьшить панель ещё раз — она стала бы втрое мельче нужного.

Зависимость задана двумя опорными точками — между ними линейная интерполяция,
за ними тот же наклон до упора в MIN/MAX. Меняешь опорную точку — меняется вся
кривая, других мест правки нет.
"""

# (логическая ВЫСОТА экрана, коэффициент).
#
# Считаем от высоты, а не от ширины: у сверхшироких мониторов (3440x1440)
# вертикального места ровно столько же, сколько у обычного 1440p, и по ширине
# панель раздувалась бы без причины.
#
# 1080p выверен на глаз и не меняется, 1440p подняли ещё на 10%.
ANCHORS = ((1080, 1.25), (1440, 1.4548))

# Границы автоматического расчёта: за опорными точками наклон тот же, но
# упирается сюда. Верхняя выбрана так, чтобы 4K (2160) укладывался целиком —
# ему наклон даёт x1.864.
AUTO_MIN = 1.20
AUTO_MAX = 1.90

# Границы ручного значения из настроек — шире, там пользователь знает, что делает.
MIN_FACTOR = 0.50
MAX_FACTOR = 3.00

_factor = ANCHORS[1][1]


def factor():
    return _factor


def set_factor(value):
    """Ставит коэффициент напрямую. Возвращает True, если он изменился."""
    global _factor
    value = max(MIN_FACTOR, min(MAX_FACTOR, float(value)))
    if abs(value - _factor) < 1e-4:
        return False
    _factor = value
    return True


def factor_for_height(height):
    """Коэффициент по логической высоте экрана."""
    (h1, f1), (h2, f2) = ANCHORS
    slope = (f2 - f1) / (h2 - h1)
    return max(AUTO_MIN, min(AUTO_MAX, f1 + (height - h1) * slope))


def set_from_screen(screen, override=0.0, user=1.0):
    """
    Пересчитывает масштаб под экран.

    override > 0 — жёсткое значение вместо расчёта по ширине.
    user — множитель с ползунка размера в настройках.
    """
    user = float(user or 1.0)
    if override and override > 0:
        return set_factor(override * user)
    if screen is None:
        return False
    return set_factor(factor_for_height(screen.geometry().height()) * user)


def s(px):
    """Целый размер в пикселях экрана (для геометрии виджетов)."""
    return int(round(px * _factor))


def sf(px):
    """Дробный размер (для шрифтов, толщины линий, радиусов при отрисовке)."""
    return px * _factor
