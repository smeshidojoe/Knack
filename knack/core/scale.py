"""
Масштаб интерфейса.

Макет нарисован под 2560 логических пикселей ширины. Коэффициент считаем от
ЛОГИЧЕСКОЙ геометрии экрана, а не физической: Qt6 сам применяет DPI-масштаб
Windows, и на 2560x1440 при 150% экран логически 1707x960. Считать от физической
ширины значило бы уменьшить панель ещё раз — она стала бы втрое мельче нужного.

Прямая пропорция ширине экрана не годится: на 1080p панель выходила мельче, чем
на 1440p, хотя монитор меньше и плашка должна быть заметнее. Поэтому зависимость
обратная и задана двумя опорными точками — между ними линейная интерполяция, за
ними тот же наклон до упора в MIN/MAX. Меняешь опорную точку — меняется вся
кривая, других мест правки нет.
"""

# (логическая ширина экрана, коэффициент)
ANCHORS = ((1920, 1.25), (2560, 1.15))

# Границы автоматического расчёта. Верхняя равна значению для 1080p: это самый
# мелкий экран, под который мы целимся, и на 1366 панель иначе занимала бы
# больше половины ширины.
AUTO_MIN = 0.95
AUTO_MAX = ANCHORS[0][1]

# Границы ручного значения из настроек — шире, там пользователь знает, что делает.
MIN_FACTOR = 0.50
MAX_FACTOR = 3.00

_factor = ANCHORS[1][1]


def factor():
    return _factor


def set_factor(value):
    """Ставит коэффициент напрямую. Возвращает True, если он изменился."""
    global _factor
    value = max(MIN_FACTOR, min(MAX_FACTOR, float(value)))
    if abs(value - _factor) < 1e-4:
        return False
    _factor = value
    return True


def factor_for_width(width):
    """Коэффициент по логической ширине экрана."""
    (w1, f1), (w2, f2) = ANCHORS
    slope = (f2 - f1) / (w2 - w1)
    return max(AUTO_MIN, min(AUTO_MAX, f1 + (width - w1) * slope))


def set_from_screen(screen, override=0.0):
    """Пересчитывает масштаб под экран. override > 0 — ручное значение из настроек."""
    if override and override > 0:
        return set_factor(override)
    if screen is None:
        return False
    return set_factor(factor_for_width(screen.geometry().width()))


def s(px):
    """Целый размер в пикселях экрана (для геометрии виджетов)."""
    return int(round(px * _factor))


def sf(px):
    """Дробный размер (для шрифтов, толщины линий, радиусов при отрисовке)."""
    return px * _factor
